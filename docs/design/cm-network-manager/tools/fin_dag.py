def covers_table():
    plan = json.loads((OUT / "REMAINING-DAG-PLAN.json").read_text())
    ab = json.loads((OUT / "AB-DAG.json").read_text())
    done = set(plan["done"])
    ab_cov = {c for v in ab["vertices"] for c in v.get("covers", [])}
    fin_cov = {c for v in V for c in v.get("covers", [])}
    decided = {"V.02": "D-V1", "I08.T01.a": "D-V1", "H.10": "D-C1", "I05.T02.a": "D-X1"}
    lines = ["", "## Что закрывает пакет в общем плане", "", "| Вершина | Закрывает подзадачи |", "|---|---|"]
    for v in V:
        if v.get("covers"):
            lines.append(f"| `{v['id']}` | {', '.join(v['covers'])} |")
    left = [t["id"] for t in plan["tasks"] if t["id"] not in done and t["id"] not in ab_cov and t["id"] not in fin_cov]
    lines += ["", "Подзадача закрывается, когда приняты все её вершины; подзадачи уровня L4 — когда пользователь прошёл соответствующий шаг очереди хоста.", "",
              "Открытые подзадачи общего плана, которых нет ни в AB, ни в FIN:", "", "| Подзадача | Что с ней |", "|---|---|"]
    for item in left:
        note = f"решение {decided[item]}" if item in decided else "**не назначена**"
        lines.append(f"| `{item}` | {note} |")
    lines.append("")
    return "\n".join(lines), [item for item in left if item not in decided]


